// Shared pieces of the deterministic emitters: naming, string literals and URL patterns.
import type { Plan } from '../../schemas/generated/index.js';

export interface EmittedFile {
  /** Path inside export/<target>/, with forward slashes. */
  path: string;
  content: string;
}

export interface EmitInput {
  plan: Plan.TestPlan;
  tests: Plan.Test[];
  runId: string;
  appUrl: string;
  conventions: { naming?: string; test_dir?: string };
}

export interface Emitter {
  target: string;
  emit(input: EmitInput): EmittedFile[];
}

/** A string literal valid in both TypeScript and C#. JSON escaping covers quotes and control characters. */
export function str(value: string): string {
  return JSON.stringify(value);
}

export function pascal(id: string): string {
  return id
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

export function camel(id: string): string {
  const p = pascal(id);
  return p.charAt(0).toLowerCase() + p.slice(1);
}

/** Environment variable holding a persona's stored session file. */
export function authEnv(persona: string): string {
  return `TESSA_AUTH_${persona.toUpperCase().replace(/[^A-Z0-9]+/g, '_')}`;
}

export function authDefault(persona: string): string {
  return `.auth/${persona}.json`;
}

/**
 * The IR's url-matches pattern applies to path and query. Playwright matches the full URL, so an
 * anchored pattern gets an origin prefix: "^/tickets/[0-9]+$" -> "^[a-z][a-z0-9+.-]*://[^/]+/tickets/[0-9]+$".
 */
export function fullUrlPattern(pathPattern: string): string {
  return pathPattern.startsWith('^')
    ? `^[a-z][a-z0-9+.-]*://[^/]+${pathPattern.slice(1)}`
    : pathPattern;
}

/** File name from the naming convention: {feature} is the story id, {scenario} the test id. */
export function fileName(
  naming: string | undefined,
  story: string,
  test: string | null,
  ext: string,
): string {
  const template = naming ?? (test === null ? '{feature}.spec' : '{feature}.{scenario}.spec');
  const name = template
    .replaceAll('{feature}', story)
    .replaceAll('{scenario}', test ?? '')
    .replace(/\.{2,}/g, '.')
    .replace(/^\.|\.$/g, '')
    .replace(/[^A-Za-z0-9._-]/g, '-');
  return `${name}${ext}`;
}

/** Comment line safe in both languages: no line breaks, no comment terminators. */
export function comment(text: string): string {
  return text.replace(/\r?\n/g, ' ').replace(/\*\//g, '* /');
}

export function header(input: EmitInput, prefix: string): string[] {
  return [
    `${prefix} Generated by Tessa from plans/${input.plan.story.id}/tests.json (run ${input.runId}).`,
    `${prefix} Story: ${comment(input.plan.story.title)}`,
    `${prefix} Sessions come from stored storage state files; see README.md. No credentials are in this file.`,
  ];
}
